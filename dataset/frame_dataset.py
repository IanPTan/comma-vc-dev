import h5py
import torch
from torch.utils.data import Dataset

class FrameDataset(Dataset):
    """
    PyTorch Dataset that loads frames from an H5 file generated by generate_dataset.py.
    Returns torch.Tensor of shape (C, H, W) normalized to [0, 1].
    """
    def __init__(self, h5_path, transform=None):
        self.h5_path = h5_path
        self.transform = transform
        
        # Read length and check file existence
        with h5py.File(self.h5_path, 'r') as f:
            if 'frames' not in f:
                raise KeyError(f"H5 file at '{self.h5_path}' does not contain 'frames' dataset.")
            self.length = f['frames'].shape[0]
            
        # File object and dataset reference are lazily initialized
        # to support PyTorch DataLoader multiprocessing (multiple workers)
        self.file = None
        self.dataset = None

    def __len__(self):
        return self.length

    def __getitem__(self, idx):
        if self.file is None:
            self.file = h5py.File(self.h5_path, 'r')
            self.dataset = self.file['frames']
            
        frame = self.dataset[idx]
        
        # Convert HWC numpy uint8 to CHW torch float32 tensor in [0.0, 1.0] range
        frame_tensor = torch.from_numpy(frame).permute(2, 0, 1).to(torch.float32) / 255.0
        
        if self.transform:
            frame_tensor = self.transform(frame_tensor)
            
        return frame_tensor
